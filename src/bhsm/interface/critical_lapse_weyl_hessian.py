def background_identity_residuals(t: sp.Expr = T) -> dict[str, sp.Expr]:
    """Exact normalized critical P1/scalar background checks."""
    a = a0(t)
    n = lapse0()
    hubble = sp.diff(a, t) / (n * a)
    return {
        "hamiltonian": sp.trigsimp(hubble**2 - sp.Integer(2) / a**2 + 1),
        "radial_evolution": sp.simplify(sp.diff(a, t, 2) / (n**2 * a) + 1),
        "scalar_background": sp.Integer(0),
        "B1_matching": sp.simplify(
            (sp.diff(a, t) / (n * a)).subs(t, 1) - sp.Integer(1)
        ),
        "critical_scalar_boundary": sp.Integer(0),
    }


