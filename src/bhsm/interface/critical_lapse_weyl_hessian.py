def a0(t: sp.Expr = T) -> sp.Expr:
    """Critical fixed-domain warp factor."""
    return sp.sqrt(2) * sp.sin(sp.pi * t / 4)


def lapse0() -> sp.Expr:
    return sp.pi / 4


def radial_weight(t: sp.Expr = T) -> sp.Expr:
    """Action measure after factoring the reference M4 measure."""
    return sp.simplify(lapse0() * a0(t) ** 4)


def determinant_factor_expansion() -> sp.Expr:
    """sqrt(det h)/[a0^4 sqrt(det hbar)] for h=(1+2 eps psi)a0^2 hbar."""
    return sp.expand((1 + 2 * EPSILON * PSI) ** 2)


def inverse_metric_factor_expansion() -> sp.Expr:
    """a0^2 h^{mu nu}/hbar^{mu nu} through O(epsilon^2)."""
