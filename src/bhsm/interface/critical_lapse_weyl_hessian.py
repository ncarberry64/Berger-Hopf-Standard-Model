def B1_endpoint_hessian() -> sp.Expr:
    """Coefficient H_B1 in (1/2) H_B1 (D psi_J)^2."""
    return 12 * C_PARTIAL


def threading_profile(
    t: sp.Expr = T,
    tau: sp.Expr = TAU,
    chi_1: sp.Expr = CHI_1,
) -> sp.Expr:
    return sp.simplify(-tau * sp.pi * chi_1 * t / 16)


def J_A_threading(
    t: sp.Expr = T,
    tau: sp.Expr = TAU,
    chi_1: sp.Expr = CHI_1,
) -> sp.Expr:
    """Action-derived threading part of the mixed lapse source."""
    b = threading_profile(t, tau, chi_1)
    h_t = sp.diff(a0(t), t) / a0(t)
    return sp.simplify(6 * KAPPA_1 * b * h_t / (lapse0() ** 2 * a0(t) ** 2))


def J_psi_threading_operator(
    t: sp.Expr = T,
    tau: sp.Expr = TAU,
    chi_1: sp.Expr = CHI_1,
) -> str:
    """Unintegrated first-radial-derivative threading source."""
    coefficient = sp.sstr(
        sp.simplify(
            -6
            * KAPPA_1
            * threading_profile(t, tau, chi_1)
            / (lapse0() ** 2 * a0(t) ** 2)
        )
    )
    return f"({coefficient})*partial_t"


