"""Actual canonical-current factor on the inherited finite temporal domain.

The first-order midpoint residual has its initial trace fixed and its final
trace free.  Its action-induced squared form retains the final adjoint face;
it is neither the old tent-Dirichlet factor nor the completed native heat.
The common Yukawa coefficients are extracted by the exact LR grading, not
by subtracting nearly equal family inverses.
"""
from __future__ import annotations

