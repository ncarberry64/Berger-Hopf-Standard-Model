FAMILY_INDICES = np.array([[2*f,2*f+1,6+2*f,7+2*f,12+2*f,13+2*f] for f in range(3)])
LR_SIGN = np.diag([1.,1.,1.,1.,-1.,-1.])


def common_current_node(phase, response_time, *, first_field_sampler=None):
    """Owned C6 Y0/Y1 body and CANONICAL magnetic delta-H coefficients.

    Xi0/Xi1 are delta H_can = delta W-i delta Omega_tau.  In particular
    their temporal At vertex is -i G/N, not the positive-factor G/N.
    The actual first-three measured-charge magnetic axes keep order 0,1,2;
    all eight source coordinates and twenty angular coefficients survive.
    """
    app=fermion_wick_application(phase,response_time,first_field_sampler=first_field_sampler)
    rep=lepton_current_hilbert_representation();fi=FAMILY_INDICES[1]
    body=app['Hcan_L'][np.ix_(fi,fi)]
    H0=(body+LR_SIGN@body@LR_SIGN)/2
    raw=app['raw_fields'];H=raw[-8:-6]+1j*raw[-6:-4]
    H1=_unit_lepton_mass6(H)
    Y=np.diag(rep['family_Y']).real
    checks=[]
    for f,indices in enumerate(FAMILY_INDICES):
        checks.append(np.max(abs(app['Hcan_L'][np.ix_(indices,indices)]-H0-Y[f]*H1)))
    result=dict(Hcan0=H0,Hcan1=H1,N=app['N'],R4=app['R4'],H=H,
        EM_source_right=-rep['EM_charge'][np.ix_(fi,fi)],
        EM_target_left=-rep['EM_charge'][np.ix_(fi,fi)],
        alpha6=rep['alpha'][:,fi][:,:,fi],family_Y=Y,
        family_reconstruction_max=float(max(checks)),current_Gram_I6=np.eye(6),
        source_vertex='unit-coupling proper-clock temporal photon Xi=-Q; electric charge not added',
        Taylor_coefficient_Y0_is_not_a_selected_H_zero_background=True)
    if first_field_sampler is not None:
        xi=app['continued_source_coefficients'][:,:,fi][:,:,:,fi]
        xi0=(xi+np.einsum('ij,ahjk,kl->ahil',LR_SIGN,xi,LR_SIGN))/2
        h=app['source_H'];hc=h[:,:2]+1j*h[:,2:]
        xi1=np.array([[_unit_lepton_mass6(a) for a in row.T] for row in hc])
        # The reverse directed vertex is the literal same indexed action
        # matrix; it is not replaced by a new conjugate/normalization.
        result.update(magnetic_Xi0=xi0,magnetic_Xi1=xi1,
            magnetic_reverse_Xi0=xi0.swapaxes(-1,-2),
            magnetic_reverse_Xi1=xi1.swapaxes(-1,-2),
            magnetic_canonical_delta_H=xi,
            magnetic_continued_delta_D_L=-xi,
            magnetic_continued_source_tau_first=app['continued_source_tau_first'][:,:,fi][:,:,:,fi],
            magnetic_family_reconstruction_max=float(np.max(abs(xi-xi0-Y[1]*xi1))),
            magnetic_source_kind='canonical delta-H, equivalently continued delta-A_E at the contour anchor; not positive-factor delta-A',
            temporal_At_placement='-i G/N',active_source_indices=[0,1,2])
    return result


def midpoint_factor_coefficients(coordinate_nodes,lapses,Hcan0,Hcan1):
    """A_E=-D_L on tau=i(t-t0), with both adjacent nodal values.

    The squared-domain final condition is generated by A's adjoint.  No
    independent final Dirichlet trace is appended.  Proper-clock source
    Gram is h*N; its common unit-Haar factor cancels the inverse identity.
    """
    t=np.asarray(coordinate_nodes,float);N=np.asarray(lapses,float)
    H0,H1=map(lambda x:np.asarray(x,complex),(Hcan0,Hcan1))
    if (t.ndim!=1 or len(t)<2 or np.any(np.diff(t)<=0) or N.shape!=(len(t)-1,)
            or H0.shape!=(len(N),6,6)or H1.shape!=H0.shape
            or not np.isfinite([*t,*N]).all()or np.any(N<=0)
            or not np.isfinite(H0).all()or not np.isfinite(H1).all()):
        raise ValueError('complete chronological nodes and actual common C6 coefficients required')
    h=np.diff(t);weight=h*N;I=np.eye(6)
    return dict(A0_diagonal=-1j*I[None]/weight[:,None,None]+H0/2,
        A0_lower=1j*I[None]/weight[:,None,None]+H0/2,
        A1_diagonal=H1/2,A1_lower=H1/2,proper_cell_weights=weight,
        coordinate_nodes=t,midpoint_coordinate_times=(t[:-1]+t[1:])/2,
        initial_trace='chi(initial)=0 for the inhomogeneous inverse',
        final_trace='free; adjoint final-face/natural squared condition retained',
        contour='tau=i*(t-t0); A_E=-D_L',physical_native_heat_identified=False)


def _first_order_matrix(diagonal,lower):
    d,l=np.asarray(diagonal),np.asarray(lower);count=len(d)
    blocks=[[None]*count for _ in range(count)]
    for j in range(count):
        blocks[j][j]=csc_matrix(d[j])
        if j:blocks[j][j-1]=csc_matrix(l[j])
    return bmat(blocks,format='csc')


def squared_current_inverse(coefficients,Y,source_right,target_left):
    """Apply the actual first-order and action-induced squared inverses.

    K=A^dagger G_source A and K^-1 A^dagger G_source R=A^-1 R on
    this identical finite initial/free-final domain.  The left current is
    supplied as a literal row map, independently of Hermitian conjugation.
    Returned finite-current contraction is an operator component, not a
    loop, selected external state, Pauli coefficient, or native regulator.
    """
    c=coefficients;y=float(Y);d=c['A0_diagonal']+y*c['A1_diagonal']
    l=c['A0_lower']+y*c['A1_lower'];R,L=map(lambda a:np.asarray(a,complex),(source_right,target_left))
    n=len(d);m=6
    if R.ndim!=3 or R.shape[:2]!=(n,m)or L.shape!=(n,R.shape[2],m):
        raise ValueError('literal source/right and target/left current maps in the same domain required')
    A=_first_order_matrix(d,l);G=diags(np.repeat(c['proper_cell_weights'],m),format='csc')
    K=(A.conj().T@G@A).tocsc();right=R.reshape(n*m,-1)
    direct=splu(A).solve(right);squared=splu(K).solve(A.conj().T@(G@right))
    residual=A@squared-right
    weighted=L*c['proper_cell_weights'][:,None,None]/2
    nodal_target=weighted+np.concatenate((weighted[1:],np.zeros_like(weighted[:1])))
    dual=splu(A.T.tocsc()).solve(nodal_target.transpose(0,2,1).reshape(n*m,-1))
    # Midpoint target uses (chi_j+chi_(j-1))/2.  The source remains a
    # residual test value; no additional Gram or canonical density enters.
    U=direct.reshape(n,m,-1);Um=(U+np.concatenate((np.zeros_like(U[:1]),U[:-1])))/2
    current=np.einsum('t,tij,tjk->ik',c['proper_cell_weights'],L,Um)
    acted=A.conj().T@(G@(A@squared-right))
    return dict(first_order_response=U,squared_response=squared.reshape(U.shape),
        literal_left_current_contraction=current,
        source_adjoint=dual.reshape(n,m,-1),
        literal_current_source_adjoint_pairing=dual.T@right,
        current_adjoint_pairing_max=float(np.max(abs(dual.T@right-current))),
        inverse_identity_max=float(np.max(abs(squared-direct))),
        first_order_residual_max=float(np.max(abs(A@direct-right))),
        squared_original_residual_max=float(np.max(abs(residual))),
        squared_variational_residual_max=float(np.max(abs(acted))),
        squared_final_face_residual=acted.reshape(n,m,-1)[-1],
        actual_free_final_value=U[-1],
        two_face_Dirichlet_imposed=False,finite_cutoff_inserted=False,
        identity='K=A†G_source A; K^-1 A†G_source R=A^-1 R',
        domain_scope='same first-order finite midpoint inverse with initial trace fixed, final trace free; K inherits all its adjoint contacts',
        physical_P_strat_or_Pauli_completed=False)


def continued_current_coefficients(phase,steps,*,first_field_sampler=None):
    """Bind all common coefficients to the saved chronological field action."""
    if type(steps)is not int or steps<2:raise ValueError('resolved temporal representation required')
    length=abs(float(phase['receipt']['span']));nodes=np.linspace(0,length,steps+1)
    points=[common_current_node(phase,float(u),first_field_sampler=first_field_sampler)
            for u in (nodes[:-1]+nodes[1:])/2]
    out=midpoint_factor_coefficients(nodes,np.array([a['N']for a in points]),
        np.array([a['Hcan0']for a in points]),np.array([a['Hcan1']for a in points]))
    keys=('Hcan0','Hcan1','N','R4','H','EM_source_right','EM_target_left',
          'magnetic_Xi0','magnetic_Xi1','magnetic_reverse_Xi0','magnetic_reverse_Xi1',
          'magnetic_continued_source_tau_first')
    out.update({key:np.array([a[key]for a in points])for key in keys if key in points[0]})
    out.update(common_Hcan0=out.pop('Hcan0'),common_Hcan1=out.pop('Hcan1'),
        source_right_map=out.pop('EM_source_right'),target_left_map=out.pop('EM_target_left'),
        family_indices=FAMILY_INDICES,family_Y=points[0]['family_Y'],canonical_Gram_I6=np.eye(6),
        alpha6=points[0]['alpha6'],family_reconstruction_max=max(a['family_reconstruction_max']for a in points),
        active_magnetic_source_indices=np.array([0,1,2]),source_electric_charge_added_again=False)
    return out
