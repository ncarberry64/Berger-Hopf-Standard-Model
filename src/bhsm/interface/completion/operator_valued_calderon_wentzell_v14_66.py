def _finite_positive(x: float, name: str) -> float:
    y = float(x)
    if not math.isfinite(y) or y <= 0.0:
        raise ValueError(f"{name} must be positive and finite")
    return y


def _as_hermitian(a: np.ndarray, name: str = "matrix", tol: float = 1e-11) -> np.ndarray:
    x = np.asarray(a, dtype=complex)
    if x.ndim != 2 or x.shape[0] != x.shape[1]:
        raise ValueError(f"{name} must be square")
    if np.linalg.norm(x - np.conjugate(x.T)) > tol:
        raise ValueError(f"{name} must be Hermitian")
    return 0.5 * (x + np.conjugate(x.T))


def _as_unitary(u: np.ndarray, name: str = "unitary", tol: float = 1e-11) -> np.ndarray:
    x = np.asarray(u, dtype=complex)
    if x.ndim != 2 or x.shape[0] != x.shape[1]:
        raise ValueError(f"{name} must be square")
    ident = np.eye(x.shape[0], dtype=complex)
    if np.linalg.norm(np.conjugate(x.T) @ x - ident) > tol:
        raise ValueError(f"{name} must be unitary")
    return x


def hermitian_function(a: np.ndarray, fn) -> np.ndarray:
    h = _as_hermitian(a)
    w, v = np.linalg.eigh(h)
    fw = np.asarray([fn(float(x)) for x in w], dtype=float)
    if not np.all(np.isfinite(fw)):
        raise ValueError("matrix function returned nonfinite values")
    return (v * fw) @ np.conjugate(v.T)


def positive_sqrt(a: np.ndarray, tol: float = 1e-12) -> np.ndarray:
    h = _as_hermitian(a)
    w = np.linalg.eigvalsh(h)
    if float(np.min(w)) < -tol:
        raise ValueError("matrix is not positive semidefinite")
    return hermitian_function(h, lambda x: math.sqrt(max(0.0, x)))


def spin_j_matrices(n: int) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    """Spin j=n/2 generators in the descending-m basis."""
    nn = int(n)
    if nn < 0:
        raise ValueError("n must be nonnegative")
    j = 0.5 * nn
    d = nn + 1
    ms = np.asarray([j - k for k in range(d)], dtype=float)
    jz = np.diag(ms).astype(complex)
    jp = np.zeros((d, d), dtype=complex)
    for col, m in enumerate(ms):
        mp = m + 1.0
        if mp <= j + 1e-14:
            rows = np.where(np.isclose(ms, mp))[0]
            if len(rows):
                jp[int(rows[0]), col] = math.sqrt(max(0.0, j * (j + 1.0) - m * (m + 1.0)))
    jm = np.conjugate(jp.T)
    jx = 0.5 * (jp + jm)
    jy = (jp - jm) / (2.0j)
    return jx, jy, jz


def berger_dirac_block(n: int, beta: float, radius: float = 1.0) -> np.ndarray:
    """Exact homogeneous Berger Dirac block used by the v14.59 geometry gate.

    Metric convention: h_beta = R^2(sigma_1^2+sigma_2^2+beta^2 sigma_3^2).
    The block is
      D_n = C I + 2 a sigma_z⊗J_z + 2 b sigma_y⊗J_y + 2 c sigma_x⊗J_x,
    with a=b=1/R, c=1/(beta R),
      C=1/2(ab/c+bc/a+ca/b).
    """
    bta = _finite_positive(beta, "beta")
    r = _finite_positive(radius, "radius")
    sx = np.array([[0.0, 1.0], [1.0, 0.0]], dtype=complex)
    sy = np.array([[0.0, -1.0j], [1.0j, 0.0]], dtype=complex)
    sz = np.array([[1.0, 0.0], [0.0, -1.0]], dtype=complex)
    jx, jy, jz = spin_j_matrices(int(n))
    a = 1.0 / r
    b = 1.0 / r
    c = 1.0 / (bta * r)
    C = 0.5 * (a * b / c + b * c / a + c * a / b)
    dim = 2 * (int(n) + 1)
    out = (
        C * np.eye(dim, dtype=complex)
        + 2.0 * a * np.kron(sz, jz)
        + 2.0 * b * np.kron(sy, jy)
        + 2.0 * c * np.kron(sx, jx)
    )
    return _as_hermitian(out, "Berger Dirac block")


def berger_n1_expected_eigenvalues(beta: float, radius: float = 1.0) -> np.ndarray:
    b = _finite_positive(beta, "beta")
    r = _finite_positive(radius, "radius")
    vals = [
        (b - 4.0) / (2.0 * r),
        (b * b + 4.0) / (2.0 * b * r),
        (b * b + 4.0) / (2.0 * b * r),
        (b + 4.0) / (2.0 * r),
    ]
    return np.asarray(sorted(vals), dtype=float)


def berger_positive_tangential(n: int, beta: float, radius: float, regulator_mass: float) -> np.ndarray:
    mu = _finite_positive(regulator_mass, "regulator_mass")
    d = berger_dirac_block(n, beta, radius)
    return positive_sqrt(d @ d + mu * mu * np.eye(d.shape[0], dtype=complex))


def plane_unitary(dim: int, i: int, j: int, theta: float, phase: float = 0.0) -> np.ndarray:
    d = int(dim)
    if d < 2 or not (0 <= i < d and 0 <= j < d) or i == j:
        raise ValueError("invalid plane rotation indices")
    th = float(theta)
    ph = float(phase)
    if not (math.isfinite(th) and math.isfinite(ph)):
        raise ValueError("rotation data must be finite")
    c, s = math.cos(th), math.sin(th)
    u = np.eye(d, dtype=complex)
    u[i, i] = c
    u[j, j] = c
    u[i, j] = -s * np.exp(-1j * ph)
    u[j, i] = s * np.exp(1j * ph)
    return _as_unitary(u)


