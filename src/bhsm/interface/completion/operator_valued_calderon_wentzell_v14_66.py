def orthogonal_complement_basis(zero_modes: np.ndarray, ambient_dim: int | None = None, tol: float = 1e-12) -> np.ndarray:
    z = np.asarray(zero_modes, dtype=complex)
    if z.ndim == 1:
        z = z[:, None]
    if z.ndim != 2:
        raise ValueError("zero_modes must be a matrix")
    n = z.shape[0] if ambient_dim is None else int(ambient_dim)
    if z.shape[0] != n:
        raise ValueError("ambient dimension mismatch")
    if z.shape[1] == 0:
        return np.eye(n, dtype=complex)
    u, s, _ = np.linalg.svd(z, full_matrices=True)
    rank = int(np.sum(s > tol))
    return u[:, rank:]


def diagnostic_zero_modes(dim: int) -> np.ndarray:
    n = len(VERTICES) * dim
    z1 = np.zeros(n, dtype=complex)
    z2 = np.zeros(n, dtype=complex)
    for vi in range(len(VERTICES)):
        z1[vi * dim + 0] = 1.0
        z2[vi * dim + 1] = (1.0, -1.0, -1.0, 1.0)[vi]
    z1 /= np.linalg.norm(z1)
    z2 /= np.linalg.norm(z2)
    return np.column_stack((z1, z2))


def projected_response_operator(h: np.ndarray, dim: int) -> tuple[np.ndarray, np.ndarray]:
    z = diagnostic_zero_modes(dim)
    q = orthogonal_complement_basis(z, h.shape[0])
    hp = np.conjugate(q.T) @ h @ q
    return _as_hermitian(hp, "projected response"), q


def matrix_heat_trace(h: np.ndarray, t: float) -> float:
    tt = _finite_positive(t, "t")
    ev = np.linalg.eigvalsh(_as_hermitian(h))
    return math.fsum(math.exp(-tt * float(x)) for x in ev)


def matrix_logdet_positive(h: np.ndarray) -> float:
    ev = np.linalg.eigvalsh(_as_hermitian(h))
    if float(np.min(ev)) <= 0.0:
        raise ValueError("positive logdet requires positive spectrum")
    return math.fsum(math.log(float(x)) for x in ev)


