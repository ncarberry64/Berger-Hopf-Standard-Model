def wilson_loop(transports: Mapping[str, np.ndarray]) -> np.ndarray:
    """Loop M8 -> M5+ -> M4 -> M5- -> M8."""
    return (
        np.conjugate(transports["e_8m"].T)
        @ np.conjugate(transports["e_m4"].T)
        @ transports["e_p4"]
        @ transports["e_8p"]
    )


def unitary_eigenphases(u: np.ndarray) -> np.ndarray:
    x = _as_unitary(u)
    vals = np.linalg.eigvals(x)
    phases = np.asarray([math.atan2(z.imag, z.real) for z in vals], dtype=float)
    return np.sort(phases)


