def kkt_schur_wentzell(dim: int, vertex_index: int = 0) -> tuple[np.ndarray, dict[str, float]]:
    """Deterministic positive KKT witness W=Hbb-Hbi Hii^-1 Hib.

    This validates the algebraic ownership route only.  The coefficients are
    frozen theorem-witness values and are not the physical BHSM Gram-Hessian.
    """
    d = int(dim)
    if d < 1:
        raise ValueError("dim must be positive")
    q = int(vertex_index)
    hbb = np.diag([0.52 + 0.035 * q + 0.021 * i for i in range(d)]).astype(complex)
    hii = np.diag([1.65 + 0.041 * q + 0.037 * i for i in range(d)]).astype(complex)
    hbi = np.zeros((d, d), dtype=complex)
    for i in range(d):
        hbi[i, i] = 0.075 + 0.004 * q + 0.003 * i
        if i + 1 < d:
            hbi[i, i + 1] = (0.018 + 0.001 * q) * np.exp(1j * (0.11 + 0.03 * i))
    w = hbb - hbi @ np.linalg.solve(hii, np.conjugate(hbi.T))
    w = _as_hermitian(w, "Wentzell Schur complement")
    ev = np.linalg.eigvalsh(w)
    return w, {
        "min_Hii_eigenvalue": float(np.min(np.linalg.eigvalsh(hii))),
        "min_W_eigenvalue": float(np.min(ev)),
        "W_hermiticity_residual": float(np.linalg.norm(w - np.conjugate(w.T))),
    }


def diagnostic_wentzell_blocks(dim: int) -> dict[str, np.ndarray]:
    return {v: kkt_schur_wentzell(dim, i)[0] for i, v in enumerate(VERTICES)}


def wentzell_extension_matrices(dim: int, wentzell: Mapping[str, np.ndarray]) -> tuple[np.ndarray, np.ndarray]:
    """A,B for vector continuity and p_i+p_j+W_v u_v=0.

    W_v is distributed as W_v/2 on the two endpoint values.  On the
    continuity subspace this is exactly W_v u_v.  Hermitian W_v implies the
    exact self-adjoint extension criterion AB*=BA*.
    """
    d = int(dim)
    n_end = 2 * len(EDGES)
    n = n_end * d
    a = np.zeros((n, n), dtype=complex)
    b = np.zeros((n, n), dtype=complex)
    row = 0
    I = np.eye(d, dtype=complex)
    for vertex in VERTICES:
        i_ep, j_ep = vertex_endpoint_indices()[vertex]
        si = slice(i_ep * d, (i_ep + 1) * d)
        sj = slice(j_ep * d, (j_ep + 1) * d)
        rr = slice(row, row + d)
        a[rr, si] = I
        a[rr, sj] = -I
        row += d
        rr = slice(row, row + d)
        w = _as_hermitian(np.asarray(wentzell[vertex]), f"W[{vertex}]")
        if w.shape != (d, d):
            raise ValueError("Wentzell block dimension mismatch")
        a[rr, si] = 0.5 * w
        a[rr, sj] = 0.5 * w
        b[rr, si] = I
        b[rr, sj] = I
        row += d
    return a, b


def wentzell_extension_diagnostics(dim: int = 6) -> dict[str, Any]:
    ws = diagnostic_wentzell_blocks(dim)
    a, b = wentzell_extension_matrices(dim, ws)
    rank = int(np.linalg.matrix_rank(np.concatenate((a, b), axis=1)))
    comm = float(np.linalg.norm(a @ np.conjugate(b.T) - b @ np.conjugate(a.T)))
    mins = {v: float(np.min(np.linalg.eigvalsh(w))) for v, w in ws.items()}
    return {
        "boundary_dimension": int(a.shape[0]),
        "rank_A_B": rank,
        "ABstar_minus_BAstar_norm": comm,
        "minimum_Wentzell_eigenvalues": mins,
        "all_Wentzell_blocks_positive": all(x > 0.0 for x in mins.values()),
        "self_adjoint_Wentzell_extension_pass": rank == a.shape[0] and comm < 1e-12,
    }


def sample_wentzell_domain_data(dim: int = 6, seed: int = 1466) -> tuple[np.ndarray, np.ndarray]:
    rng = np.random.default_rng(seed)
    d = int(dim)
    n_end = 2 * len(EDGES)
    g0 = np.zeros(n_end * d, dtype=complex)
    g1 = np.zeros(n_end * d, dtype=complex)
    ws = diagnostic_wentzell_blocks(d)
    for vertex in VERTICES:
        i_ep, j_ep = vertex_endpoint_indices()[vertex]
        si = slice(i_ep * d, (i_ep + 1) * d)
        sj = slice(j_ep * d, (j_ep + 1) * d)
        u = rng.normal(size=d) + 1j * rng.normal(size=d)
        p = rng.normal(size=d) + 1j * rng.normal(size=d)
        g0[si] = u
        g0[sj] = u
        g1[si] = p
        g1[sj] = -ws[vertex] @ u - p
    return g0, g1


