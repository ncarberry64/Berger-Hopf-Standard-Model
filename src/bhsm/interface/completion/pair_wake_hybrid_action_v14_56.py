def _finite(values: Iterable[float]) -> bool:
    return all(math.isfinite(float(value)) for value in values)


def normalize_phase(value: float) -> float:
    if not math.isfinite(value):
        raise ValueError("finite phase required")
    return value % (2.0 * math.pi)


def identity(n: int = 3) -> Matrix:
    if n <= 0:
        raise ValueError("positive dimension required")
    return tuple(
        tuple(1.0 + 0j if i == j else 0j for j in range(n)) for i in range(n)
    )


def dagger(matrix: Sequence[Sequence[complex]]) -> Matrix:
    if not matrix:
        raise ValueError("nonempty matrix required")
    rows = len(matrix)
    cols = len(matrix[0])
    if any(len(row) != cols for row in matrix):
        raise ValueError("rectangular matrix required")
    return tuple(
        tuple(complex(matrix[i][j]).conjugate() for i in range(rows))
        for j in range(cols)
    )


def matmul(a: Sequence[Sequence[complex]], b: Sequence[Sequence[complex]]) -> Matrix:
    if not a or not b:
        raise ValueError("nonempty matrices required")
    a_rows = len(a)
    a_cols = len(a[0])
    b_rows = len(b)
    b_cols = len(b[0])
    if any(len(row) != a_cols for row in a) or any(len(row) != b_cols for row in b):
        raise ValueError("rectangular matrices required")
    if a_cols != b_rows:
        raise ValueError("incompatible matrix dimensions")
    return tuple(
        tuple(
            sum(complex(a[i][k]) * complex(b[k][j]) for k in range(a_cols))
            for j in range(b_cols)
        )
        for i in range(a_rows)
    )


def matvec(matrix: Sequence[Sequence[complex]], vector: Sequence[complex]) -> Vector:
    if not matrix or len(matrix[0]) != len(vector):
        raise ValueError("incompatible matrix/vector dimensions")
    return tuple(
        sum(complex(value) * complex(vector[j]) for j, value in enumerate(row))
        for row in matrix
    )


def matsub(a: Sequence[Sequence[complex]], b: Sequence[Sequence[complex]]) -> Matrix:
    if len(a) != len(b) or any(len(x) != len(y) for x, y in zip(a, b)):
        raise ValueError("equal matrix dimensions required")
    return tuple(
        tuple(complex(x) - complex(y) for x, y in zip(row_a, row_b))
        for row_a, row_b in zip(a, b)
    )


def frobenius_norm(matrix: Sequence[Sequence[complex]]) -> float:
    return math.sqrt(
        sum(abs(complex(value)) ** 2 for row in matrix for value in row)
    )


def unitarity_residual(matrix: Sequence[Sequence[complex]]) -> float:
    if not matrix or len(matrix) != len(matrix[0]):
        raise ValueError("nonempty square matrix required")
    product = matmul(dagger(matrix), matrix)
    return frobenius_norm(matsub(product, identity(len(matrix))))


def commutator_norm(a: Sequence[Sequence[complex]], b: Sequence[Sequence[complex]]) -> float:
    return frobenius_norm(matsub(matmul(a, b), matmul(b, a)))


def diagonal_unitary(phases: Sequence[float]) -> Matrix:
    if not phases or not _finite(phases):
        raise ValueError("finite phases required")
    n = len(phases)
    return tuple(
        tuple(cmath.exp(-1j * phases[i]) if i == j else 0j for j in range(n))
        for i in range(n)
    )


def rotation_12(theta: float, phase: float = 0.0) -> Matrix:
    if not _finite((theta, phase)):
        raise ValueError("finite rotation parameters required")
    c = math.cos(theta)
    s = math.sin(theta)
    e_minus = cmath.exp(-1j * phase)
    e_plus = e_minus.conjugate()
    return (
        (c + 0j, s * e_minus, 0j),
        (-s * e_plus, c + 0j, 0j),
        (0j, 0j, 1.0 + 0j),
    )


def rotation_13(theta: float, phase: float = 0.0) -> Matrix:
    if not _finite((theta, phase)):
        raise ValueError("finite rotation parameters required")
    c = math.cos(theta)
    s = math.sin(theta)
    e_minus = cmath.exp(-1j * phase)
    e_plus = e_minus.conjugate()
    return (
        (c + 0j, 0j, s * e_minus),
        (0j, 1.0 + 0j, 0j),
        (-s * e_plus, 0j, c + 0j),
    )


def rotation_23(theta: float, phase: float = 0.0) -> Matrix:
    if not _finite((theta, phase)):
        raise ValueError("finite rotation parameters required")
    c = math.cos(theta)
    s = math.sin(theta)
    e_minus = cmath.exp(-1j * phase)
    e_plus = e_minus.conjugate()
    return (
        (1.0 + 0j, 0j, 0j),
        (0j, c + 0j, s * e_minus),
        (0j, -s * e_plus, c + 0j),
    )


