def free_wake_propagator(
    elapsed_proper_time: float,
    angular_frequencies: Sequence[float],
    detector_basis: Sequence[Sequence[complex]],
) -> Matrix:
    if not math.isfinite(elapsed_proper_time) or elapsed_proper_time < 0.0:
        raise ValueError("finite nonnegative elapsed proper time required")
    if len(angular_frequencies) != 3 or not _finite(angular_frequencies):
        raise ValueError("three finite angular frequencies required")
    basis = tuple(tuple(complex(value) for value in row) for row in detector_basis)
    if unitarity_residual(basis) > 1e-10:
        raise ValueError("unitary detector basis required")
    phases = [omega * elapsed_proper_time for omega in angular_frequencies]
    return matmul(basis, matmul(diagonal_unitary(phases), dagger(basis)))


def state_probabilities(state: Sequence[complex]) -> tuple[float, float, float]:
    if len(state) != 3:
        raise ValueError("three-component wake state required")
    raw = tuple(abs(complex(value)) ** 2 for value in state)
    total = sum(raw)
    if total <= 0.0:
        raise ValueError("nonzero wake state required")
    return tuple(float(value / total) for value in raw)  # type: ignore[return-value]


def probability_distance(a: Sequence[float], b: Sequence[float]) -> float:
    if len(a) != len(b):
        raise ValueError("equal probability vectors required")
    return math.sqrt(sum((float(x) - float(y)) ** 2 for x, y in zip(a, b)))


@dataclass(frozen=True)
class CoherentPhaseMap:
    """Invertible orientation-preserving phase kick on S^1.

    phi_plus = phi_minus + offset + modulation*sin(phi_minus+orientation)

    |modulation| < 1 guarantees a positive Jacobian everywhere, so the map is
    invertible and is eligible to be embedded in a conservative canonical
    collision map. This is a kinematic contract, not an action-derived law.
    """

    offset: float
    modulation: float
    orientation: float = 0.0

    def validate(self) -> None:
        if not _finite((self.offset, self.modulation, self.orientation)):
            raise ValueError("finite phase-map parameters required")
        if abs(self.modulation) >= 1.0:
            raise ValueError("|modulation| < 1 required for global invertibility")

    def apply(self, phase: float) -> float:
        self.validate()
        phi = normalize_phase(phase)
        return normalize_phase(
            phi + self.offset + self.modulation * math.sin(phi + self.orientation)
        )

    def jacobian(self, phase: float) -> float:
        self.validate()
        phi = normalize_phase(phase)
        return 1.0 + self.modulation * math.cos(phi + self.orientation)

    def globally_invertible(self) -> bool:
        self.validate()
        return 1.0 - abs(self.modulation) > 0.0


@dataclass(frozen=True)
class CoherentMatterImpulse:
    momentum_kick: Vector3
    phase_map: CoherentPhaseMap
    wake_angle_12: float
    wake_angle_23: float
    wake_phase: float

    def validate(self) -> None:
        if not _finite((*self.momentum_kick, self.wake_angle_12, self.wake_angle_23, self.wake_phase)):
            raise ValueError("finite coherent impulse required")
        self.phase_map.validate()

    def wake_unitary(self) -> Matrix:
        self.validate()
        return matmul(
            rotation_23(self.wake_angle_23, -0.5 * self.wake_phase),
            rotation_12(self.wake_angle_12, self.wake_phase),
        )


@dataclass(frozen=True)
class HybridPairWakeState:
    proper_time: float
    scalar_phase: float
    momentum: Vector3
    wake_state: Vector
    pair_identity: tuple[str, str]
    internal_relation_tag: str

    def validate(self) -> None:
        if not _finite((self.proper_time, self.scalar_phase, *self.momentum)):
            raise ValueError("finite hybrid pair-wake state required")
        if len(self.wake_state) != 3:
            raise ValueError("three-component wake state required")
        if abs(sum(abs(value) ** 2 for value in self.wake_state) - 1.0) > 1e-10:
            raise ValueError("normalized wake state required")
        if len(self.pair_identity) != 2 or not all(self.pair_identity):
            raise ValueError("fixed two-member pair identity required")
        if not self.internal_relation_tag:
            raise ValueError("nonempty internal relation tag required")


def free_evolve_hybrid_state(
    state: HybridPairWakeState,
    elapsed_proper_time: float,
    scalar_frequency: float,
    angular_frequencies: Sequence[float],
    detector_basis: Sequence[Sequence[complex]],
) -> HybridPairWakeState:
    state.validate()
    if not _finite((elapsed_proper_time, scalar_frequency)) or elapsed_proper_time < 0.0:
        raise ValueError("finite nonnegative propagation data required")
    propagator = free_wake_propagator(
        elapsed_proper_time, angular_frequencies, detector_basis
    )
    evolved = matvec(propagator, state.wake_state)
    norm = math.sqrt(sum(abs(value) ** 2 for value in evolved))
    evolved = tuple(value / norm for value in evolved)
    return HybridPairWakeState(
        proper_time=state.proper_time + elapsed_proper_time,
        scalar_phase=normalize_phase(
            state.scalar_phase + scalar_frequency * elapsed_proper_time
        ),
        momentum=state.momentum,
        wake_state=evolved,
        pair_identity=state.pair_identity,
        internal_relation_tag=state.internal_relation_tag,
    )


def apply_coherent_matter_impulse(
    state: HybridPairWakeState,
    impulse: CoherentMatterImpulse,
) -> HybridPairWakeState:
    state.validate()
    impulse.validate()
    kick = impulse.wake_unitary()
    kicked = matvec(kick, state.wake_state)
    norm = math.sqrt(sum(abs(value) ** 2 for value in kicked))
    kicked = tuple(value / norm for value in kicked)
    return HybridPairWakeState(
        proper_time=state.proper_time,
        scalar_phase=impulse.phase_map.apply(state.scalar_phase),
        momentum=tuple(
            component + delta
            for component, delta in zip(state.momentum, impulse.momentum_kick)
        ),  # type: ignore[arg-type]
        wake_state=kicked,
        pair_identity=state.pair_identity,
        internal_relation_tag=state.internal_relation_tag,
    )


