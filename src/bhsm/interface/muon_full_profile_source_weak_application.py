"""Full supplied child-profile source in the original two-arm action dual.

The three input slots are independently supplied functions: gauge value,
Eulerian time derivative, and radial derivative.  No finite coefficient
restriction, additional material advection, or tangent conjugation occurs.
The source arrays are held fixed when differentiating the action coordinates.
"""
from __future__ import annotations

import numpy as np

from .muon_holomorphic_normal_geometry import (
    holomorphic_geometry_rows, holomorphic_cap_and_weights,
)
from .muon_nonlinear_chronological_n0_action import analytic_constant_maxwell_batch
from .muon_nonlinear_n0_field_action import analytic_intrinsic_n0_jet
from .muon_parent_maxwell_full_weak import M
from .muon_parent_mean_causal_action import MAXWELL_TO_CAP
from .muon_parent_retarded_hypercharge import WALL


def full_profile_source_weak_application(raw_pair, rep, action, field_source,
        wall_source, *, nu_squared_action=4):
    """Apply a held full source to value and all raw536/master504 gradients.

    ``field_source`` has shape (3, Nrho, 5, 4), and ``wall_source`` has
    shape (3, 5, 4).  The existing intrinsic scalar action uses the wall
    VALUE slot; its time/radial slots remain exported functions and are
    not invented scalar action coordinates.  Scalar/Higgs gradient contacts
    generated by the wall value are retained in the full action dual.

    A source depending on the actual raw pair additionally requires its
    own coordinate derivative.  This helper does not assign that term zero:
    it implements the supplied-functions-held partial only.
    """
    raw = np.asarray(raw_pair, complex)
    source = np.asarray(field_source, complex)
    wall = np.asarray(wall_source, complex)
    rho = np.asarray(rep['rho'])
    weights_r = np.asarray(rep['radial_quadrature'])
    lift = np.asarray(action['master_lift'], complex)
    if (raw.shape != (2, 268) or source.shape != (3, len(rho), 5, 4)
            or wall.shape != (3, 5, 4) or weights_r.shape != (len(rho),)
            or lift.shape != (536, 504)
            or not all(np.isfinite(x).all() for x in (raw, source, wall, lift))):
        raise ValueError('complete raw536 graph, full three-slot functions, exact wall and master504 lift required')
    if not np.isfinite(nu_squared_action) or nu_squared_action < 0:
        raise ValueError('assigned nonnegative intrinsic scalar parameter required')

    # These are exactly the current child fields of the completed graph.
    fields = action['branch_fields'][1]
    A, At, Ar = (np.asarray(fields[k], complex) for k in ('A', 'At', 'Ar'))
    if any(x.shape != (len(rho), 5, 4) for x in (A, At, Ar)):
        raise ValueError('same current graph child field nodes required')
    held = source.transpose(1, 0, 2, 3).reshape(len(rho), 60)
    parent = holomorphic_geometry_rows(raw[0, :100], rho, connection_only=True)
    parent_wall = holomorphic_geometry_rows(raw[0, :100], [WALL], connection_only=True)
    geometry = holomorphic_geometry_rows(raw[1, :100], rho)
    names = ('electric', 'radial', 'angular', 'electric_radial', 'shift')
    density = np.array([[row[k].value for k in names] for row in geometry['rows']])
    local = analytic_constant_maxwell_batch(A, At, Ar, density)

    # The density polarization is exact: linear in its first four slots
    # and quadratic in beta.  Unit beta steps carry no truncation error.
    gdc = np.empty((len(rho), 60, 5), complex)
    for k in range(4):
        unit = np.zeros_like(density)
        unit[:, k] = 1
        unit[:, 4] = density[:, 4]
        gdc[:, :, k] = analytic_constant_maxwell_batch(A, At, Ar, unit)['gradient']
    plus, minus = density.copy(), density.copy()
    plus[:, 4] += 1
    minus[:, 4] -= 1
    gdc[:, :, 4] = (
        analytic_constant_maxwell_batch(A, At, Ar, plus)['gradient']
        - analytic_constant_maxwell_batch(A, At, Ar, minus)['gradient']) / 2

    gb = np.asarray(rep['gauge_basis'])[:, :, 0].reshape(len(rho), 80, 20)
    gr = np.asarray(rep['gauge_radial_basis'])[:, :, 0].reshape(len(rho), 80, 20)
    raw_gradient = np.zeros(536, complex)
    maxwell_value = 0j
    keys = ('connection_lambda', 'lambda_tau', 'lambda_rho')
    for j, weight in enumerate(weights_r):
        factor = weight * MAXWELL_TO_CAP
        J = np.zeros((60, 100), complex)
        for k, key in enumerate(keys):
            J[k * 20 + 8:(k + 1) * 20] = (
                M.reshape(12, 1) * parent['rows'][j][key].gradient[None, :])
        acted = local['hessian'][j] @ held[j]
        raw_gradient[:100] += factor * J.T @ acted
        raw_gradient[368:448] += factor * (gb[j] @ acted[:20] + gr[j] @ acted[40:])
        raw_gradient[448:528] += factor * gb[j] @ acted[20:40]
        df = np.array([geometry['rows'][j][k].gradient for k in names])
        raw_gradient[268:368] += factor * df.T @ gdc[j].T @ held[j]
        maxwell_value += factor * (local['gradient'][j] @ held[j])

    cap = holomorphic_cap_and_weights(raw[1, :100], points=rep['cap_points'])
    scalar_weights = [cap[k] for k in ('wT', 'wS', 'wV')]
    args = dict(lambda_H=rep['scalar_matching']['lambda_H'],
                nu_squared_action=nu_squared_action)
    scalar = analytic_intrinsic_n0_jet(
        fields['wall'], raw[1, 260:264], raw[1, 264:],
        np.array([w.value for w in scalar_weights]), **args)
    wall_direction = np.zeros(28, complex)
    wall_direction[4:24] = wall[0].reshape(20)
    J = np.zeros((28, 100), complex)
    J[12:24] = (M.reshape(12, 1)
                  * parent_wall['rows'][0]['connection_lambda'].gradient[None, :])
    S = np.zeros((28, 168), complex)
    S[:4, 160:164] = np.eye(4)
    S[4:24, :80] = np.asarray(rep['wall_trace_map']).reshape(20, 80)
    S[24:, 164:] = np.eye(4)
    acted = scalar['hessian'] @ wall_direction
    raw_gradient[:100] += J.T @ acted
    raw_gradient[368:] += S.T @ acted
    for j, weight in enumerate(scalar_weights):
        part = analytic_intrinsic_n0_jet(
            fields['wall'], raw[1, 260:264], raw[1, 264:], np.eye(3)[j], **args)
        raw_gradient[268:368] += weight.gradient * (part['gradient'] @ wall_direction)
    scalar_value = scalar['gradient'] @ wall_direction

    return dict(value_clock_first=maxwell_value + scalar_value,
        maxwell_value_source_first=maxwell_value, scalar_value_source_first=scalar_value,
        raw_gradient_clock_first=raw_gradient,
        gradient_clock_first=lift.T @ raw_gradient,
        full_material_field_source=source.copy(), full_material_wall_source=wall.copy(),
        source_slot_names=('value', 'Eulerian_time', 'radial'),
        scalar_wall_value_source=wall[0].copy(),
        scalar_wall_time_and_radial_slots_are_retained_outputs=True,
        source_functions_held_for_raw_partial=True,
        source_raw_derivative_if_dependent_is_not_supplied=True,
        actual_parent_partial_clock_count=0, material_advection_added_count=0,
        source_coefficients_conjugated=False, finite_coefficient_restriction_used=False,
        independent_Higgs_value_source_not_supplied=True,
        Higgs_action_gradient_and_coupled_response_retained=True,
        cap_and_mechanical_baseline_explicit_source_first=0j,
        physical_source_or_mode_or_domain_selected=False)
